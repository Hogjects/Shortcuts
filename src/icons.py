_bundled = set()
if os.path.isdir(_ICON_DIR):
    _bundled = {f[:-4] for f in os.listdir(_ICON_DIR) if f.endswith(".svg")}


def setup():
    """Registers the bundled icon directory with GTK. Needs a display, so
    call it from Gtk.Application.do_startup."""
    display = Gdk.Display.get_default()
    if display is not None:
        Gtk.IconTheme.get_for_display(display).add_search_path(ICON_ROOT)


def resolve(name):
    """Bundled icon name for `name`. Names that are already bundled, or that
    belong to a plugin and aren't known here, pass through unchanged (the
    latter then fall back to the system icon theme)."""
    if not name:
        return DEFAULT_ICON
    if name in _bundled:
        return name
    return LEGACY.get(name, name)


# --- Launched apps' own icons -------------------------------------------

def find_app(display_name):
    import action_library  # local import: action_library is the one that knows the installed apps
    return action_library.INSTALLED_APPS.get(display_name)


def app_gicon(display_name):
    """The Gio.Icon of an installed app, or None."""
    info = find_app(display_name)
    return info.get_icon() if info is not None else None


def app_icon_name(display_name):
    return APP_PREFIX + display_name


def _fit(image, pixel_size):
    image.set_pixel_size(pixel_size)
    return image


def image(name, pixel_size=16):
    """A Gtk.Image for an icon name. "app:<Name>" shows that installed app's
    own icon (full colour); everything else is a bundled symbolic icon."""
    if name and name.startswith(APP_PREFIX):
        gicon = app_gicon(name[len(APP_PREFIX):])
        if gicon is not None:
            img = _fit(Gtk.Image.new_from_gicon(gicon), pixel_size)
            img.add_css_class("app-icon")
            return img
        name = FALLBACK_APP_ICON
    return _fit(Gtk.Image.new_from_icon_name(resolve(name)), pixel_size)


def set_button_icon(button, name):
    button.set_icon_name(resolve(name))


def step_icon_name(step, action_type):
    """Icon for a step: the chosen app's own icon for "Open App", else the
    action's bundled icon."""
    if action_type.id == "script.open_app":
        pv = step.params.get("app")
        if pv is not None and getattr(pv, "kind", "literal") == "literal" and pv.value:
            return app_icon_name(str(pv.value))
    return action_type.icon_name


def auto_icon_for(shortcut, action_by_id):
    """(icon_name, color_class) that best represents a shortcut: taken from
    its first meaningful step. Comments are skipped."""
    for step in shortcut.steps:
        at = action_by_id.get(step.action_id)
        if at is None or at.id == "script.comment":
            continue
        return step_icon_name(step, at), at.color_class
    return DEFAULT_ICON, "tile-blue"
